"""
Pack orbit_flat.py's icons into the TypeScript module the web draws from.

  python3 orbit_flat_ts.py <icons.json> <out.ts>

Per character and variant: the base layers (body, accessories, the one tonal
shade) once, and only the eye layers per state, since a state changes the eyes
and nothing else (the pose is motion, done by the page). Coordinates are
rounded to 0.1 of the 64-unit box (sharp to well past 48 px). Plain Python.
"""

import json
import re
import sys

EYES = ("eye", "white", "pupil")


def round_path(d):
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)


src, out = sys.argv[1], sys.argv[2]
data = json.load(open(src))
packed = {}
for variant, chars in data.items():
    packed[variant] = {}
    for cid, states in chars.items():
        first = states.get("ready") or next(iter(states.values()))
        base = [[f, round_path(d), r] for f, d, r in first["layers"] if not r.startswith(EYES)]
        eyes = {st: [[f, round_path(d)] for f, d, r in ic["layers"] if r.startswith(EYES)] for st, ic in states.items()}
        # the base layer order, with where the eyes go (above the body, below front parts)
        roles = [r for f, d, r in first["layers"]]
        at = next((i for i, r in enumerate(roles) if r.startswith(EYES)), len(roles))
        eye_at = len([r for r in roles[:at] if not r.startswith(EYES)])
        packed[variant][cid] = {"base": base, "eyeAt": eye_at, "eyes": eyes}

with open(out, "w") as fh:
    fh.write("/* Generated by tools/crew/blender/orbit_flat.py + orbit_flat_ts.py from the 3D Orbit agents. Do not edit by hand. */\n")
    fh.write("/* eslint-disable */\n")
    fh.write("export type OrbitIconLayer = [fill: string, d: string, role: string];\n")
    fh.write("export interface OrbitIconData {\n  base: OrbitIconLayer[];\n  /** Index in `base` the eye layers are drawn at (above the body, under front parts). */\n  eyeAt: number;\n  eyes: Record<string, [fill: string, d: string][]>;\n}\n")
    fh.write('/** `full` for 48 px, `small` for 28 px and under (bigger eyes, fine parts dropped). 64-unit box. */\n')
    fh.write('export const ORBIT_ICONS: Record<"full" | "small", Record<string, OrbitIconData>> = ')
    fh.write(json.dumps(packed, separators=(",", ":"), ensure_ascii=False))
    fh.write(";\n")
print("wrote", out)
