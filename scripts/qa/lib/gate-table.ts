// The generated gate table in scripts/qa/README.md (spec P0 (8)): every gate,
// its owner and its enforce/report state, computed from budgets.ts and the
// e2e/wave2/*/gates.ts files.

import { GATES, type GateDefinition } from "../../../e2e/support/budgets";
import { gateMode, type GateConfig } from "../../../e2e/support/gates";

export const README_START = "<!-- gates:start (generated by `npx tsx scripts/qa/gates.ts readme --write`; do not edit by hand) -->";
export const README_END = "<!-- gates:end -->";

/**
 * Text for one Markdown table cell. Backslashes are escaped before pipes, so a
 * backslash already in the text can never turn the added escape into a
 * literal backslash followed by a column break (CodeQL
 * js/incomplete-sanitization on PR #99).
 */
export function cell(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

export function stateOf(config: GateConfig, gate: GateDefinition): string {
  if (gate.platform === "ci") return `external (${gate.harness})`;
  return gateMode(config, gate.id) === "enforce" ? `enforced by ${config.enforcedBy.get(gate.id)?.join(", ")}` : "report-only";
}

export function gateTable(config: GateConfig): string {
  const rows = [
    "| Gate | What | Budget | Measured by | Platform | Owner (§9) | State |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const gate of GATES as readonly GateDefinition[]) {
    rows.push(
      `| \`${gate.id}\` | ${cell(gate.title)} | ${cell(gate.budget)} | ${cell(gate.measuredBy)} | ${gate.platform} | ${gate.owners.join(", ")} | ${cell(stateOf(config, gate))} |`
    );
  }
  return rows.join("\n");
}

export function renderReadme(current: string, config: GateConfig): string {
  const start = current.indexOf(README_START);
  const end = current.indexOf(README_END);
  if (start < 0 || end < start) throw new Error("scripts/qa/README.md is missing the gates:start / gates:end markers.");
  return `${current.slice(0, start)}${README_START}\n${gateTable(config)}\n${current.slice(end)}`;
}
