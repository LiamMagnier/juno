import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { CONTINUUM_OPTICAL, CONTINUUM_MASTER_PATHS, CONTINUUM_SQUARE_VIEWBOX } from "../src/components/brand/continuum-geometry.ts";
import { ALEVR_WORDMARK } from "../src/components/brand/alevr-wordmark-geometry.ts";

/*
 * Projects the Alevr brand geometry into Swift for the native apps:
 * the Continuum mark (the master in its square box, plus the 16/20/24/32
 * optical masters) and the outlined "Alevr" wordmark.
 *
 *   node scripts/generate-native-brand-geometry.mjs           regenerate
 *   node scripts/generate-native-brand-geometry.mjs --check   verify
 */
const target = fileURLToPath(new URL("../native/Packages/JunoNativeKit/Sources/JunoDesignSystem/JunoBrandGeometry.swift", import.meta.url));
const [originX, originY] = CONTINUUM_SQUARE_VIEWBOX.split(" ").map(Number);
function coordinates(path, normalize = false) {
  assert.match(path, /^M[-\d. ]+(?:C[-\d. ]+)+Z$/);
  const numbers = path.match(/-?\d+(?:\.\d+)?/g).map(Number);
  assert.equal((numbers.length - 2) % 6, 0, "Expected move point followed by cubic segments");
  return numbers.map((n, i) => normalize ? Number((n - (i % 2 === 0 ? originX : originY)).toFixed(4)) : n);
}
const masters = new Map([[0, CONTINUUM_MASTER_PATHS.map(p => coordinates(p.d, true))]]);
for (const size of [16, 20, 24, 32]) {
  assert.equal(CONTINUUM_OPTICAL[size].blades.length, 4);
  masters.set(size, CONTINUUM_OPTICAL[size].blades.map(p => coordinates(p.d)));
}
const continuum = Array.from(masters, ([size, blades]) => `        ${size}: [\n${blades.map(points => `            [${points.join(", ")}]`).join(",\n")}\n        ]`).join(",\n");
const b = ALEVR_WORDMARK.bounds;
const glyphs = ALEVR_WORDMARK.glyphs.map(g => {
  assert.match(g.d, /^[MLHVCQZ\d. -]+$/, `glyph ${g.ch} uses a command the native parser does not read`);
  return `        "${g.d}"`;
}).join(",\n");

const updated = `// GENERATED by scripts/generate-native-brand-geometry.mjs from
// src/components/brand/continuum-geometry.ts and alevr-wordmark-geometry.ts.
// Do not edit by hand: change the web geometry and regenerate.
import CoreGraphics

enum JunoBrandGeometry {
    /// The Continuum mark's four blades as \`M x y\` then cubic segments.
    /// Key 0 is the master in its square box (${CONTINUUM_SQUARE_VIEWBOX.split(" ")[2]} units a side, the
    /// mass lifted as the web's \`CONTINUUM_SQUARE_VIEWBOX\`); 16, 20, 24 and 32
    /// are the optical masters, in pixels of a box that size.
    static let continuum: [Int: [[CGFloat]]] = [
${continuum}
    ]

    /// The master square's side, in master units.
    static let continuumMasterSide: CGFloat = ${CONTINUUM_SQUARE_VIEWBOX.split(" ")[2]}

    /// The "Alevr" wordmark's ink bounds, in font units (y down, baseline 0).
    static let wordmarkBounds = CGRect(x: ${b.x}, y: ${b.y}, width: ${b.width}, height: ${b.height})

    /// One outline per glyph — A, l, e, v, r — as SVG path data (M L Q C Z).
    static let wordmark: [String] = [
${glyphs}
    ]
}
`;
const source = await readFile(target, "utf8").catch(() => "");
if (process.argv.includes("--check")) {
  assert.equal(source, updated, "Native brand geometry drifted; run node scripts/generate-native-brand-geometry.mjs");
  console.log("Native brand geometry matches the web's Continuum masters and the Alevr wordmark.");
} else {
  await writeFile(target, updated);
  console.log("Generated native brand geometry.");
}
