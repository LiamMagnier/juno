/**
 * Emits the Swift half of the capability manifest.
 *
 * Both halves derive from `contracts/capabilities/juno-capabilities-v1.json`,
 * so the TypeScript and Swift definitions cannot disagree: there is one file
 * to change and two outputs that follow from it. The alternative — two
 * hand-maintained enums — drifts silently, and drifts in the worst possible
 * way, because a Swift client that does not recognise a degradation kind shows
 * the user nothing rather than showing them something wrong.
 *
 *   node scripts/generate-capability-contract.mjs --output=<path>.swift
 */
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const manifestPath = resolve("contracts/capabilities/juno-capabilities-v1.json");
const outputArg = process.argv.find((value) => value.startsWith("--output="));
if (!outputArg) {
  throw new Error("Pass --output=/absolute/path/to/JunoCapabilityContract.swift");
}
const outputPath = resolve(outputArg.slice("--output=".length));

const source = await readFile(manifestPath, "utf8");
const manifest = JSON.parse(source);

if (typeof manifest.version !== "number") {
  throw new Error("Capability manifest is missing a numeric version.");
}
if (!Array.isArray(manifest.reasoningLevels) || manifest.reasoningLevels.length === 0) {
  throw new Error("Capability manifest is missing reasoningLevels.");
}
if (!Array.isArray(manifest.degradationKinds) || manifest.degradationKinds.length === 0) {
  throw new Error("Capability manifest is missing degradationKinds.");
}

/** Digest of the manifest text, so a client can prove which one it was built from. */
const digest = createHash("sha256").update(source).digest("hex");

const swiftCase = (key) =>
  key.replace(/_([a-z])/g, (_, character) => character.toUpperCase());

const escape = (value) => String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

const reasoningCases = manifest.reasoningLevels
  .map((level) => `    case ${swiftCase(level)} = "${escape(level)}"`)
  .join("\n");

const degradationCases = manifest.degradationKinds
  .map((entry) => {
    const note = entry.note ? `\n    /// ${entry.note}` : "";
    return `    /// ${entry.summary}${note}\n    case ${swiftCase(entry.key)} = "${escape(entry.key)}"`;
  })
  .join("\n");

const capabilityCases = manifest.capabilities
  .map((entry) => `    /// ${entry.summary}\n    case ${swiftCase(entry.key)} = "${escape(entry.key)}"`)
  .join("\n");

const swift = `// Generated by scripts/generate-capability-contract.mjs. Do not edit.
//
// Source of truth: contracts/capabilities/juno-capabilities-v1.json
// The TypeScript half (src/lib/effective-capabilities.ts) derives from the same
// file, so the two cannot drift. CI regenerates this and fails on a diff.
import Foundation

public enum JunoCapabilityContract {
    /// Bumped whenever a capability is added or its meaning changes.
    public static let version = ${manifest.version}
    /// SHA-256 of the manifest this was generated from.
    public static let digest = "${digest}"
}

/// A thinking effort, lowest to highest.
public enum JunoReasoningLevel: String, Codable, CaseIterable, Sendable, Comparable {
${reasoningCases}

    /// Ordering follows the manifest's own order, so "is this above the
    /// model's ceiling" is answered the same way on both platforms.
    private var rank: Int {
        JunoReasoningLevel.allCases.firstIndex(of: self) ?? 0
    }

    public static func < (lhs: JunoReasoningLevel, rhs: JunoReasoningLevel) -> Bool {
        lhs.rank < rhs.rank
    }
}

/// Something a turn can ask for that the runtime may not be able to honour.
public enum JunoCapability: String, Codable, CaseIterable, Sendable {
${capabilityCases}
}

/// Why what ran differs from what was asked for.
public enum JunoDegradationKind: String, Codable, CaseIterable, Sendable {
${degradationCases}
}

/// One difference between the requested and the effective execution.
public struct JunoDegradation: Codable, Hashable, Sendable {
    public let kind: JunoDegradationKind
    public let requested: String
    public let effective: String
    public let reason: String

    public init(
        kind: JunoDegradationKind,
        requested: String,
        effective: String,
        reason: String
    ) {
        self.kind = kind
        self.requested = requested
        self.effective = effective
        self.reason = reason
    }
}

/// What actually ran, as the server resolved it.
public struct JunoEffectiveCapabilities: Codable, Hashable, Sendable {
    public let version: Int
    public let modelID: String
    public let provider: String
    public let reasoning: JunoReasoningLevel?
    public let webSearch: Bool
    public let fastMode: Bool
    public let vision: Bool
    public let connectors: Bool
    public let degradations: [JunoDegradation]

    /// True when anything the user asked for did not happen.
    public var wasDegraded: Bool { !degradations.isEmpty }

    private enum CodingKeys: String, CodingKey {
        case version
        case modelID = "modelId"
        case provider
        case reasoning
        case webSearch
        case fastMode
        case vision
        case connectors
        case degradations
    }

    public init(
        version: Int,
        modelID: String,
        provider: String,
        reasoning: JunoReasoningLevel?,
        webSearch: Bool,
        fastMode: Bool,
        vision: Bool,
        connectors: Bool,
        degradations: [JunoDegradation]
    ) {
        self.version = version
        self.modelID = modelID
        self.provider = provider
        self.reasoning = reasoning
        self.webSearch = webSearch
        self.fastMode = fastMode
        self.vision = vision
        self.connectors = connectors
        self.degradations = degradations
    }

    /// Decoding tolerates a newer server.
    ///
    /// A manifest version above this build's means the server may send a
    /// degradation kind this client has never heard of. Dropping those rather
    /// than failing the whole decode is the difference between "one row of the
    /// explanation is missing" and "the reply will not load".
    public init(from decoder: any Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        version = try container.decode(Int.self, forKey: .version)
        modelID = try container.decode(String.self, forKey: .modelID)
        provider = try container.decode(String.self, forKey: .provider)
        reasoning = try container.decodeIfPresent(JunoReasoningLevel.self, forKey: .reasoning)
        webSearch = try container.decodeIfPresent(Bool.self, forKey: .webSearch) ?? false
        fastMode = try container.decodeIfPresent(Bool.self, forKey: .fastMode) ?? false
        vision = try container.decodeIfPresent(Bool.self, forKey: .vision) ?? false
        connectors = try container.decodeIfPresent(Bool.self, forKey: .connectors) ?? false
        degradations =
            (try container.decodeIfPresent([LenientDegradation].self, forKey: .degradations) ?? [])
            .compactMap(\\.value)
    }
}

/// Decodes one degradation, yielding nil instead of throwing on a kind this
/// build does not know.
///
/// Decoding \`[JunoDegradation?]\` does NOT do this: an optional element
/// tolerates a JSON \`null\`, not a nested decode failure, so a single
/// unrecognised \`kind\` still failed the whole array — and with it the entire
/// message. The wrapper is what turns "a newer server" into a missing line of
/// explanation rather than a reply that will not load.
private struct LenientDegradation: Decodable {
    let value: JunoDegradation?

    init(from decoder: any Decoder) throws {
        value = try? JunoDegradation(from: decoder)
    }
}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, swift, "utf8");
console.log(`Wrote ${outputPath} (manifest v${manifest.version}, digest ${digest.slice(0, 12)}…)`);
