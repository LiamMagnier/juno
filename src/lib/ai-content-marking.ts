/**
 * Machine-readable "AI-generated" marking for the files /api/generate writes
 * (EU AI Act, Regulation 2024/1689, art. 50(2): outputs of a generative AI
 * system are "marked in a machine-readable format and detectable as
 * artificially generated or manipulated").
 *
 * What this does, per format, with no dependency and no re-encoding (the
 * pixels are never touched):
 *
 *   PNG   an iTXt "XML:com.adobe.xmp" chunk carrying an XMP packet, and a
 *         tEXt "ai-generated" = "true" chunk, inserted before the first IDAT
 *         (readers such as libvips only look for metadata ahead of the data).
 *   JPEG  an APP1 XMP segment, inserted after SOI (and after APP0/JFIF, which
 *         must stay first).
 *   WebP  an "XMP " chunk, with the VP8X header created or flagged for it.
 *
 * The XMP says what the IPTC standard says AI output should say:
 * Iptc4xmpExt:DigitalSourceType = trainedAlgorithmicMedia (or
 * compositeWithTrainedAlgorithmicMedia for an edit of a person's own image),
 * the vocabulary Google, Adobe, Meta and OpenAI read. No account, prompt or
 * person is written into the file: the marking says what made it, not who.
 *
 * What it deliberately does NOT do:
 *
 *   - Touch a file that already carries a C2PA manifest (PNG caBX, JPEG APP11
 *     JUMBF, WebP C2PA). The provider's signed provenance is the stronger
 *     marking, and inserting bytes would break its hash binding.
 *   - Video and audio (MP4, MP3, WAV…). Those are returned untouched; the
 *     providers that make them (Veo/Lyria with SynthID, and others) mark them
 *     at the source or not at all, and writing a container box safely needs a
 *     real muxer. See docs/pricing/LEGAL_CHECKLIST.md § AI Act.
 *
 * A malformed file is returned unchanged rather than "fixed": a marking step
 * must never be the reason a generation fails.
 */

export interface MarkingInput {
  /** The model that made it, e.g. "GPT Image 2". Written as the creator tool. */
  generator: string;
  /** True when the output is an edit of an image the person supplied. */
  edited?: boolean;
  /** The product name, e.g. "Alevr". */
  product: string;
}

export interface MarkingResult {
  bytes: Buffer;
  /** What happened, for logs and tests. */
  marked: "xmp" | "skipped-c2pa" | "skipped-unsupported" | "skipped-already" | "skipped-malformed";
}

export const IPTC_TRAINED_ALGORITHMIC = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";
export const IPTC_COMPOSITE_TRAINED_ALGORITHMIC =
  "http://cv.iptc.org/newscodes/digitalsourcetype/compositeWithTrainedAlgorithmicMedia";

const XMP_NS_HEADER = "http://ns.adobe.com/xap/1.0/\0";
/** Present in every packet this module writes: the idempotence check. */
const OUR_MARK = "Iptc4xmpExt:DigitalSourceType";

function xmlEscape(value: string): string {
  return value.replace(/[<>&"']/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&apos;" })[c]!);
}

/** The XMP packet. Exported for tests. */
export function aiXmpPacket(input: MarkingInput): string {
  const source = input.edited ? IPTC_COMPOSITE_TRAINED_ALGORITHMIC : IPTC_TRAINED_ALGORITHMIC;
  const tool = xmlEscape(`${input.product} (${input.generator})`);
  const description = input.edited ? "Edited with generative AI" : "Generated by AI";
  return (
    '<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>' +
    '<x:xmpmeta xmlns:x="adobe:ns:meta/">' +
    '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">' +
    '<rdf:Description rdf:about=""' +
    ' xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"' +
    ' xmlns:xmp="http://ns.adobe.com/xap/1.0/"' +
    ' xmlns:dc="http://purl.org/dc/elements/1.1/"' +
    ` Iptc4xmpExt:DigitalSourceType="${source}"` +
    ` xmp:CreatorTool="${tool}">` +
    `<dc:description><rdf:Alt><rdf:li xml:lang="x-default">${description}</rdf:li></rdf:Alt></dc:description>` +
    "</rdf:Description></rdf:RDF></x:xmpmeta>" +
    '<?xpacket end="r"?>'
  );
}

