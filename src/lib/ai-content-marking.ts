/** Mark one generated file. Never throws; an unknown or broken file comes back unchanged. */
export function markAiGenerated(bytes: Buffer, mimeType: string, input: MarkingInput): MarkingResult {
  try {
    const type = mimeType.toLowerCase();
    if (type === "image/png") return markPng(bytes, input);
    if (type === "image/jpeg" || type === "image/jpg") return markJpeg(bytes, input);
    if (type === "image/webp") return markWebp(bytes, input);
    return { bytes, marked: "skipped-unsupported" };
  } catch {
    return { bytes, marked: "skipped-malformed" };
  }
}
